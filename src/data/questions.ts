/**
 * Les packs de questions — le cœur de Flirt.
 *
 * Chaque pack a un identifiant stable (utilisé pour les achats in-app et la
 * sauvegarde locale), un niveau d'intensité indicatif et une liste de
 * questions. Les packs `premium: true` sont verrouillés tant qu'ils n'ont
 * pas été achetés (voir src/services/purchases.ts).
 */

export interface QuestionPack {
  id: string;
  title: string;
  emoji: string;
  description: string;
  /** 1 = tout doux, 3 = intense */
  intensity: 1 | 2 | 3;
  /**
   * Questions qui se jouent naturellement à deux (« Tu préfères »,
   * débats…) : la carte s'adresse alors aux deux joueurs au lieu
   * d'alterner. C'est la mécanique « Mix » du jeu.
   */
  duo?: boolean;
  premium: boolean;
  /** Identifiant produit App Store / Play Store, pour les packs premium. */
  productId?: string;
  questions: string[];
}

