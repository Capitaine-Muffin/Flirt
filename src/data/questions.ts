/**
 * Les packs de questions — le cœur de Flirt.
 *
 * Chaque pack a un identifiant stable (utilisé pour les achats in-app et la
 * sauvegarde locale), un niveau d'intensité indicatif et une liste de
 * questions. Les packs `premium: true` ne sont pas encore disponibles :
 * ils sont annoncés « bientôt » dans l'app (voir ShopScreen).
 *
 * Mécanique « Mix » : chaque pack mélange des questions solo (une chaîne
 * de caractères — une personne répond, en alternance) et des questions
 * duo (`{ text, duo: true }` — les deux répondent). C'est la nature de
 * chaque question qui décide.
 */

export type QuestionEntry = string | { text: string; duo: true };

export function questionText(q: QuestionEntry): string {
  return typeof q === 'string' ? q : q.text;
}

export function isDuo(q: QuestionEntry): boolean {
  return typeof q !== 'string' && q.duo;
}

export interface QuestionPack {
  id: string;
  title: string;
  emoji: string;
  description: string;
  /** 1 = tout doux, 3 = intense */
  intensity: 1 | 2 | 3;
  premium: boolean;
  /** Identifiant produit App Store / Play Store, pour les packs premium. */
  productId?: string;
  questions: QuestionEntry[];
}

